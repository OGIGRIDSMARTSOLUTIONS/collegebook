const { z } = require('zod');

const createInstitutionSchema = z.object({
  institutionCode: z.string().min(2).max(20).toUpperCase(),
  name: z.string().min(2),
  shortName: z.string().optional(),
  location: z.string().optional(),
  website: z.string().url().optional(),
});

const createFacultySchema = z.object({
  name: z.string().min(1).max(160),
});

const updateFacultySchema = z.object({
  name: z.string().min(1).max(160),
});

const createDepartmentSchema = z.object({
  name: z.string().min(1).max(160),
  facultyId: z.string().min(1),
});

const updateDepartmentSchema = z.object({
  name: z.string().min(1).max(160),
});

const updateInstitutionBrandingSchema = z.object({
  logoUrl: z.string().url().nullable().optional(),
  coverImageUrl: z.string().url().nullable().optional(),
});

const createAcademicSetSchema = z.object({
  // The administrator only supplies the academic year. The display name,
  // internal code and CLASS kind are generated by the backend.
  name: z.string().min(1).max(120).optional(),
  startYear: z.number().int().min(1900).max(2200),
});


const createInstitutionAdminSchema = z.object({
  firstName: z.string().trim().min(1).max(80),
  lastName: z.string().trim().min(1).max(80),
  email: z.string().trim().email().max(254),
  password: z.string().min(8, 'Password must be at least 8 characters').max(128),
});

module.exports = {
  createInstitutionSchema,
  createInstitutionAdminSchema,
  createFacultySchema,
  updateFacultySchema,
  createDepartmentSchema,
  updateDepartmentSchema,
  createAcademicSetSchema,
  updateInstitutionBrandingSchema,
};
